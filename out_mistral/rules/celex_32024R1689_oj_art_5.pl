    ai_system(S),
    has_objective_or_effect_of_materially_distorting_behaviour(S),
    appreciably_impairs_informed_decision_ability(S),
    causes_decision_not_otherwise_taken(S),
    causes_or_likely_to_cause_significant_harm(S).

